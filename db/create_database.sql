CREATE FUNCTION increment_project_version() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE s466402.c_repair_projects AS project
    SET current_version = current_version + 1
    FROM s466402.c_repair_works AS work
    WHERE work.id = NEW.source_work_id AND project.id = work.project_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER change_request_done
AFTER UPDATE OF status ON c_change_requests
FOR EACH ROW
WHEN (OLD.status <> 'DONE' AND NEW.status = 'DONE')
EXECUTE FUNCTION increment_project_version();

CREATE FUNCTION prevent_element_cycle() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    ancestor_id bigint := NEW.parent_id;
BEGIN
    WHILE ancestor_id IS NOT NULL LOOP
        IF ancestor_id = NEW.id THEN
            RAISE EXCEPTION 'Цикл в иерархии: элемент % является своим предком', NEW.id
                USING ERRCODE = 'check_violation';
        END IF;

        SELECT parent.parent_id INTO ancestor_id
        FROM s466402.c_facility_elements AS parent
        WHERE parent.id = ancestor_id
        FOR NO KEY UPDATE;
    END LOOP;

    RETURN NEW;
END;
$$;

CREATE TRIGGER facility_element_no_cycle
AFTER INSERT OR UPDATE OF id, parent_id ON c_facility_elements
FOR EACH ROW
WHEN (NEW.parent_id IS NOT NULL)
EXECUTE FUNCTION prevent_element_cycle();

CREATE FUNCTION ready_repair_works(p_contractor_id bigint, p_project_id bigint)
RETURNS SETOF s466402.c_repair_works
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT work.*
    FROM s466402.c_repair_works AS work
    WHERE work.contractor_id = p_contractor_id
      AND work.project_id = p_project_id
      AND work.status = 'ASSIGNED'
      AND NOT EXISTS (
          SELECT 1
          FROM s466402.c_work_dependencies AS dependency
          JOIN s466402.c_repair_works AS predecessor ON predecessor.id = dependency.predecessor_id
          WHERE dependency.successor_id = work.id
            AND predecessor.status <> 'ACCEPTED'
      );
END;
$$;

CREATE PROCEDURE register_acceptance(
    p_work_id bigint,
    p_expert_id bigint,
    p_result s466402.c_acceptance_result,
    p_remarks text DEFAULT NULL,
    p_correction_deadline date DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_result IS NULL THEN
        RAISE EXCEPTION 'Укажите результат приёмки';
    END IF;

    IF p_result = 'REWORK' AND (
        NULLIF(btrim(p_remarks), '') IS NULL
        OR p_correction_deadline IS NULL
    ) THEN
        RAISE EXCEPTION 'Для доработки нужны замечания и срок исправления';
    END IF;

    UPDATE s466402.c_repair_works
    SET status = p_result::text::s466402.c_repair_work_status
    WHERE id = p_work_id AND status = 'ON_ACCEPTANCE';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Работа % не найдена или не ожидает приёмки', p_work_id;
    END IF;

    INSERT INTO s466402.c_acceptances (work_id, expert_id, acceptance_date, result, remarks, correction_deadline)
    VALUES (p_work_id, p_expert_id, CURRENT_DATE, p_result, p_remarks, p_correction_deadline);
END;
$$;

CREATE FUNCTION tender_bids(p_tender_id bigint)
RETURNS TABLE (
    bid_id bigint,
    company_name text,
    price numeric,
    duration_days integer,
    start_date date,
    warranty_months integer
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY
    SELECT bid.id, contractor.company_name, bid.price, bid.duration_days,
           bid.start_date, bid.warranty_months
    FROM s466402.c_bids AS bid
    JOIN s466402.c_contractors AS contractor ON contractor.id = bid.contractor_id
    WHERE bid.tender_id = p_tender_id
    ORDER BY bid.price;
END;
$$;

